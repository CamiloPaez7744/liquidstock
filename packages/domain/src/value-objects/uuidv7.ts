/**
 * RFC 9562 UUIDv7 generator (time-ordered, offline-safe, zero external deps).
 * Works identically in Node.js (Fastify API) and Browser/PWA (IndexedDB Outbox).
 */
export function generateUuidV7(nowMs: number = Date.now()): string {
  const bytes = new Uint8Array(16);

  if (typeof globalThis.crypto !== "undefined" && typeof globalThis.crypto.getRandomValues === "function") {
    globalThis.crypto.getRandomValues(bytes);
  } else {
    for (let i = 0; i < 16; i += 1) {
      bytes[i] = Math.floor(Math.random() * 256);
    }
  }

  // 48-bit big-endian Unix timestamp in milliseconds
  const ts = BigInt(nowMs);
  bytes[0] = Number((ts >> 40n) & 0xffn);
  bytes[1] = Number((ts >> 32n) & 0xffn);
  bytes[2] = Number((ts >> 24n) & 0xffn);
  bytes[3] = Number((ts >> 16n) & 0xffn);
  bytes[4] = Number((ts >> 8n) & 0xffn);
  bytes[5] = Number(ts & 0xffn);

  // Version 7 (0111)
  bytes[6] = ((bytes[6] ?? 0) & 0x0f) | 0x70;
  // Variant RFC 4122 (10xx)
  bytes[8] = ((bytes[8] ?? 0) & 0x3f) | 0x80;

  const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

